
CREATE DATABASE project_archive;
USE project_archive;
SELECT DATABASE();

CREATE TABLE STUDENT (
    student_id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    phone VARCHAR(15),
    enroll_no VARCHAR(30) NOT NULL,
    year INT NOT NULL,
    department VARCHAR(100) NOT NULL,
    date_of_joining DATE
);

CREATE TABLE TEAM (
    team_id INT PRIMARY KEY AUTO_INCREMENT,
    team_name VARCHAR(100) NOT NULL,
    joined_on DATE,
    created_on DATE NOT NULL
);

CREATE TABLE DOMAIN (
    domain_id INT PRIMARY KEY AUTO_INCREMENT,
    domain_name VARCHAR(100) NOT NULL,
    description VARCHAR(500)
);

CREATE TABLE GUIDE (
    guide_id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100),
    phone VARCHAR(15),
    designation VARCHAR(100),
    department VARCHAR(100)
);

SHOW TABLES;


CREATE TABLE TECHNOLOGY (
    Tech_id INT PRIMARY KEY AUTO_INCREMENT,
    Tech_name VARCHAR(100) NOT NULL,
    Category VARCHAR(100)
);

CREATE TABLE COMPETITION (
    Competition_id INT PRIMARY KEY AUTO_INCREMENT,
    Name VARCHAR(150) NOT NULL,
    Theme VARCHAR(200),
    Start_date DATE,
    End_date DATE,
    Level VARCHAR(50),
    Organized_by VARCHAR(150),
    Year INT
);

